#!/usr/bin/env python3
"""Bake pooled NCI reference maps (nci_reference_regions.py output) into VIAMD's built-in scatter-plot reference.

Reads <REGIONS_DIR>/summary.json and one <Category>.npy per category (bins x bins, row = s bin, column = signed-rho
bin), normalises each category to unit sum, and writes the C++ source that nci_surface::reference_data() returns.

With --subfamilies, also the per-branch sub-maps of subfamily_regions.py (its summary.json and sub_<n>.npy)
and, when present, level2/ refinements with their parent class names.

Usage: bake_reference.py REGIONS_DIR [OUT_CPP] [--source TEXT] [--subfamilies SUBFAMILY_DIR]
  OUT_CPP defaults to src/components/topology/nci_reference_data_core.cpp in this repository.
"""
import argparse
import json
import os
import sys

import numpy as np

CATEGORIES = ["Hydrogen bonds", "Rings", "\u03c0 interactions", "Other"]
REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DEFAULT_OUT = os.path.join(REPO, "src", "components", "topology", "nci_reference_data_core.cpp")


def npy_name(category):
    return category.replace(" ", "_") + ".npy"


def c_string(text):
    """A C string literal in plain ASCII; each escaped byte closes its literal so no hex digit can extend it."""
    out = "\""
    for b in text.encode():
        ch = chr(b)
        if ch in "\\\"":
            out += "\\" + ch
        elif 32 <= b < 127:
            out += ch
        else:
            out += f"\\x{b:02X}\" \""
    return out + "\""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("regions")
    ap.add_argument("out", nargs="?", default=DEFAULT_OUT)
    ap.add_argument("--source", default="", help="provenance text stored with the map")
    ap.add_argument("--subfamilies", default=None, help="subfamily_regions.py output directory")
    ap.add_argument("--extended", action="store_true", help="emit extended_reference_data instead of reference_data")
    args = ap.parse_args()

    with open(os.path.join(args.regions, "summary.json")) as f:
        summary = json.load(f)
    bins = int(summary["bins"])
    fields, systems = [], []
    for category in CATEGORIES:
        field = np.load(os.path.join(args.regions, npy_name(category))).astype(np.float64)
        if field.shape != (bins, bins) or not np.all(np.isfinite(field)) or (field < 0).any():
            sys.exit(f"{category}: expected a finite non-negative {bins}x{bins} field")
        total = field.sum()
        fields.append(field / total if total > 0 else field)
        systems.append(int(summary["categories"].get(category, {}).get("systems", 0)))
    subfamilies = []
    if args.subfamilies:
        with open(os.path.join(args.subfamilies, "summary.json")) as f:
            sub_summary = json.load(f)
        if int(sub_summary["bins"]) != bins:
            sys.exit("subfamilies: bins differ from the categories'")
        entries = [(args.subfamilies, sub) for sub in sub_summary["subfamilies"]]
        finer_dir = os.path.join(args.subfamilies, "level2")
        if os.path.isfile(os.path.join(finer_dir, "summary.json")):
            with open(os.path.join(finer_dir, "summary.json")) as f:
                finer = json.load(f)
            if any(finer[key] != sub_summary[key] for key in ("bins", "rho_extent", "s_max")):
                sys.exit("level2: grid differs from the top-level subfamilies'")
            parents = {(sub["category"], sub["name"]) for sub in sub_summary["subfamilies"]}
            for sub in finer["subfamilies"]:
                if (sub["category"], sub.get("parent")) not in parents:
                    sys.exit(f"level2: {sub['name']} has no matching parent class")
            entries += [(finer_dir, sub) for sub in finer["subfamilies"]]
        for directory, sub in entries:
            field = np.load(os.path.join(directory, sub["file"])).astype(np.float64)
            if field.shape != (bins, bins) or not np.all(np.isfinite(field)) or (field < 0).any() or field.sum() <= 0:
                sys.exit(f"{sub['name']}: expected a finite non-negative non-empty {bins}x{bins} field")
            subfamilies.append((CATEGORIES.index(sub["category"]), sub["name"], int(sub["systems"]),
                                float(sub.get("overlap") or 0.0), field / field.sum(), sub.get("parent", "")))

    # Escaped so the generated source is plain ASCII
    lines = [
        "// Generated by tools/nci_reference/bake_reference.py; do not edit. Regenerate from a pooled reference run:",
        "//   tools/nci_reference/run_batch.py ... && tools/nci_reference/bake_reference.py OUT/regions-TAG",
        "// Per category, the (signed rho, s) density of its reference samples, normalised to unit sum:",
        "// field[x + bins * y], x the signed-rho bin over [-rho_extent, rho_extent], y the s bin over [0, s_max].",
        "",
        "#include \"nci_surface_core.h\"",
        "",
        "namespace nci_surface {",
        "",
        "namespace {",
        "",
    ]
    named = [(f"field_{c}", field) for c, field in enumerate(fields)]
    named += [(f"subfamily_field_{i}", s[4]) for i, s in enumerate(subfamilies)]
    for var, field in named:
        lines.append(f"constexpr float {var}[{bins * bins}] = {{")
        flat = field.reshape(-1)
        for i in range(0, flat.size, 8):
            lines.append("    " + ", ".join("0" if v == 0 else f"{v:.6g}f" for v in flat[i:i + 8]) + ",")
        lines.append("};")
        lines.append("")
    if subfamilies:
        lines.append(f"constexpr ReferenceSubfamilyData subfamilies[{len(subfamilies)}] = {{")
        for i, (c, name, n, overlap, _, parent) in enumerate(subfamilies):
            lines.append(f"    {{{c}, {c_string(name)}, {n}, {overlap:.3f}f, subfamily_field_{i}, {c_string(parent)}}},")
        lines.append("};")
        lines.append("")
    lines += [
        "}  // namespace",
        "",
        f"const ReferenceData& {'extended_reference_data' if args.extended else 'reference_data'}() {{",
        "    static const ReferenceData data = {",
        f"        {bins}, {float(summary['rho_extent'])!r}f, {float(summary['s_max'])!r}f,",
        "        {" + ", ".join(c_string(c) for c in CATEGORIES) + "},",
        "        {" + ", ".join(str(s) for s in systems) + "},",
        "        {" + ", ".join(f"field_{c}" for c in range(len(CATEGORIES))) + "},",
        f"        {c_string(args.source)},",
        *(["        subfamilies,"] if subfamilies else []),
        "    };",
        "    return data;",
        "}",
        "",
        "}  // namespace nci_surface",
        "",
    ]
    with open(args.out, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {args.out}: {bins}x{bins}, systems {dict(zip(CATEGORIES, systems))}, {len(subfamilies)} subfamilies")


if __name__ == "__main__":
    main()
